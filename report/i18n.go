type translator func(key string, args ...any) string

func newTranslator(lang string) translator {
	table, ok := messages[lang]
	if !ok {
		table = messages["en"]
	}
	return func(key string, args ...any) string {
		msg, ok := table[key]
		if !ok {
			msg, ok = messages["en"][key]
		}
		if !ok {
			return key
		}
		if len(args) == 0 {
			return msg
		}
		return fmt.Sprintf(msg, args...)
	}
}
